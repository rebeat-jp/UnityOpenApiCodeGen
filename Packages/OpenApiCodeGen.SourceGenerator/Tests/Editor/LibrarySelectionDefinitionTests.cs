        [Test]
        public void StrictJsonParserDecodesEscapesWithoutAJsonLibrary()
        {
            SpecNode root = StrictJsonSpecParser.Parse(
                "{\"plain\":\"abc\",\"esc\":\"a\\\"b\\\\c\\/d\\b\\f\\n\\r\\t\",\"u\":\"\\u0041\\u00e9\\u3042\"," +
                "\"pair\":\"\\ud83d\\ude00\",\"raw\":\"\u00e9\u3042\ud83d\ude00\"}",
                "Assets/Specs/openapi.json");
            var values = new Dictionary<string, string>();
            foreach (SpecProperty property in ((SpecObjectNode)root).Properties)
            {
                values[property.Name] = ((SpecStringNode)property.Value).Value;
            }

            Assert.That(values["plain"], Is.EqualTo("abc"));
            Assert.That(values["esc"], Is.EqualTo("a\"b\\c/d\b\f\n\r\t"));
            Assert.That(values["u"], Is.EqualTo("A\u00e9\u3042"));
            Assert.That(values["pair"], Is.EqualTo("\ud83d\ude00"));
            Assert.That(values["raw"], Is.EqualTo("\u00e9\u3042\ud83d\ude00"));
        }

        [TestCase("{\"a\":1,}")]
        [TestCase("{\"a\":01}")]
        [TestCase("{\"a\":\"\\x\"}")]
        [TestCase("{\"a\":\"\\u12G4\"}")]
        [TestCase("{\"a\":\"tab\there\"}")]
        [TestCase("{\"a\":1} trailing")]
        [TestCase("{/*c*/\"a\":1}")]
        [TestCase("{\"a\":1,\"a\":2}")]
        [TestCase("[1,2")]
        [TestCase("{\"a\":\"unterminated}")]
        public void StrictJsonParserStillRejectsInvalidDocuments(string source)
        {
            Assert.Throws<NormalizedSpecException>(
                () => StrictJsonSpecParser.Parse(source, "Assets/Specs/openapi.json"));
        }

        [Test]
        public void StrictJsonParserEnforcesTheNestingLimitWithoutAJsonLibrary()
        {
            string deep = new string('[', 300) + new string(']', 300);
            Assert.Throws<NormalizedSpecException>(
                () => StrictJsonSpecParser.Parse(deep, "Assets/Specs/openapi.json"));
            string allowed = new string('[', 100) + new string(']', 100);
            Assert.DoesNotThrow(() => StrictJsonSpecParser.Parse(allowed, "Assets/Specs/openapi.json"));
        }

        OpenApiClientDefinitionPlan Prepare(
            OpenApiHttpTransport transport,
            OpenApiJsonSerializer serializer,
            OpenApiDocumentFormat format = OpenApiDocumentFormat.Json)
        {
            return writer.Prepare(outputFolder, "PetStoreApi", Namespace, format, transport, serializer);
        }

        string ComputeIdentity()
        {
            // Same inputs the writer hashes; read from a plan to avoid duplicating the algorithm.
            return Prepare(OpenApiHttpTransport.HttpClient, OpenApiJsonSerializer.NewtonsoftJson)
                .ClientIdentitySha256;
        }

        static string Normalize(string value)
        {
            return value.Replace("\r\n", "\n");
        }

        static void WriteAsmdef(string directory, string assemblyName, string referenceJson, string extra)
        {
            Directory.CreateDirectory(directory);
            string json = string.Format(
                CultureInfo.InvariantCulture,
                "{{\n  \"name\": \"{0}\",\n  \"references\": [{1}]{2}\n}}\n",
                assemblyName,
                referenceJson,
                extra);
            File.WriteAllText(
                Path.Combine(directory, assemblyName + ".asmdef"),
                json,
                new UTF8Encoding(false));
        }
