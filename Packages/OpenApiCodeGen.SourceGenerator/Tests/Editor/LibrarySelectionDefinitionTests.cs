    /// <summary>
    /// The library selection in the owned definition file: written only when it is not the default, and read
    /// back from both the original and the extended form.
    /// </summary>
    internal sealed class LibrarySelectionDefinitionTests
    {
        const string Namespace = "Example.Generated.PetStore";
        const string Prefix = "global::Rhycol.OpenApiCodeGen.SourceGenerator.";

        string projectRoot = string.Empty;
        string outputFolder = string.Empty;
        OpenApiClientDefinitionWriter writer = null!;

        [SetUp]
        public void SetUp()
        {
            projectRoot = Path.Combine(
                Path.GetTempPath(),
                "LibrarySelectionDefinitionTests",
                Guid.NewGuid().ToString("N"));
            outputFolder = Path.Combine(projectRoot, "Assets", "Clients", "PetStore");
            Directory.CreateDirectory(outputFolder);
            WriteAsmdef(
                Path.Combine(projectRoot, "Assets", "Clients"),
                "Example.Clients",
                "\"Unity.OpenApiCodeGen.SourceGenerator\"",
                string.Empty);
            writer = new OpenApiClientDefinitionWriter(
                projectRoot,
                new AtomicFileWriter(),
                _ => { });
        }

        [TearDown]
        public void TearDown()
        {
            if (Directory.Exists(projectRoot))
            {
                Directory.Delete(projectRoot, true);
            }
        }

        [Test]
        public void DefaultSelectionWritesTheOriginalFormatByteForByte()
        {
            OpenApiClientDefinitionPlan plan = Prepare(
                OpenApiHttpTransport.HttpClient,
                OpenApiJsonSerializer.NewtonsoftJson);

            string expected =
                "// <auto-generated by UnityOpenApiCodeGen.SourceGenerator>\n" +
                "// Client identity SHA-256: " + plan.ClientIdentitySha256 + "\n" +
                "// Spec ID: " + plan.SpecId + "\n" +
                "// Changes to this file will be replaced by the next Generate operation.\n" +
                "#if OPENAPI_CODEGEN_SOURCE_GENERATOR\n" +
                "namespace " + Namespace + "\n" +
                "{\n" +
                "    [" + Prefix + "OpenApiClientDefinitionAttribute(\n" +
                "        \"" + plan.SpecId + "\",\n" +
                "        \"PetStoreApi\",\n" +
                "        \"" + Namespace + "\",\n" +
                "        " + Prefix + "OpenApiDocumentFormat.Json)]\n" +
                "    public partial class PetStoreApi\n" +
                "    {\n" +
                "    }\n" +
                "}\n" +
                "#endif\n";
            Assert.That(Normalize(Encoding.UTF8.GetString(plan.Content)), Is.EqualTo(expected));
            Assert.That(
                Encoding.UTF8.GetString(plan.Content),
                Does.Not.Contain("HttpTransport").And.Not.Contain("JsonSerializer"));
        }

        [Test]
        public void ThePlanWithoutSelectionArgumentsEqualsTheDefaultSelection()
        {
            OpenApiClientDefinitionPlan legacy = writer.Prepare(
                outputFolder,
                "PetStoreApi",
                Namespace,
                OpenApiDocumentFormat.Yaml);
            OpenApiClientDefinitionPlan explicitDefault = Prepare(
                OpenApiHttpTransport.HttpClient,
                OpenApiJsonSerializer.NewtonsoftJson,
                OpenApiDocumentFormat.Yaml);
            Assert.That(explicitDefault.Content, Is.EqualTo(legacy.Content));
        }

        [TestCase(OpenApiHttpTransport.UnityWebRequest, OpenApiJsonSerializer.NewtonsoftJson,
            "        HttpTransport = " + Prefix + "OpenApiHttpTransport.UnityWebRequest)]\n")]
        [TestCase(OpenApiHttpTransport.HttpClient, OpenApiJsonSerializer.SystemTextJson,
            "        JsonSerializer = " + Prefix + "OpenApiJsonSerializer.SystemTextJson)]\n")]
        [TestCase(OpenApiHttpTransport.UnityWebRequest, OpenApiJsonSerializer.SystemTextJson,
            "        HttpTransport = " + Prefix + "OpenApiHttpTransport.UnityWebRequest,\n" +
            "        JsonSerializer = " + Prefix + "OpenApiJsonSerializer.SystemTextJson)]\n")]
        public void NonDefaultSelectionWritesOnlyTheNonDefaultNamedArguments(
            OpenApiHttpTransport transport,
            OpenApiJsonSerializer serializer,
            string expectedNamedArguments)
        {
            OpenApiClientDefinitionPlan plan = Prepare(transport, serializer);
            string source = Normalize(Encoding.UTF8.GetString(plan.Content));

            Assert.That(
                source,
                Does.Contain(
                    "        " + Prefix + "OpenApiDocumentFormat.Json,\n" + expectedNamedArguments +
                    "    public partial class PetStoreApi"));
            Assert.That(plan.HttpTransport, Is.EqualTo(transport));
            Assert.That(plan.JsonSerializer, Is.EqualTo(serializer));
        }

        [TestCase(OpenApiHttpTransport.HttpClient, OpenApiJsonSerializer.NewtonsoftJson)]
        [TestCase(OpenApiHttpTransport.UnityWebRequest, OpenApiJsonSerializer.NewtonsoftJson)]
        [TestCase(OpenApiHttpTransport.HttpClient, OpenApiJsonSerializer.SystemTextJson)]
        [TestCase(OpenApiHttpTransport.UnityWebRequest, OpenApiJsonSerializer.SystemTextJson)]
        public void WrittenDefinitionIsReadBackAndRegeneratesWithoutChange(
            OpenApiHttpTransport transport,
            OpenApiJsonSerializer serializer)
        {
            OpenApiClientDefinitionPlan first = Prepare(transport, serializer);
            Assert.That(writer.Publish(first), Is.True);

            OpenApiClientDefinitionPlan again = Prepare(transport, serializer);

            Assert.That(again.SpecId, Is.EqualTo(first.SpecId));
            Assert.That(again.PreparedDefinitionExists, Is.True);
            Assert.That(again.RequiresPublication, Is.False);
            Assert.That(writer.Publish(again), Is.False);
        }

        [Test]
        public void ChangingTheSelectionRewritesTheDefinitionAndKeepsTheSpecId()
        {
            OpenApiClientDefinitionPlan original = Prepare(
                OpenApiHttpTransport.HttpClient,
                OpenApiJsonSerializer.NewtonsoftJson);
            Assert.That(writer.Publish(original), Is.True);
            byte[] originalBytes = File.ReadAllBytes(original.DefinitionPath);

            OpenApiClientDefinitionPlan switched = Prepare(
                OpenApiHttpTransport.UnityWebRequest,
                OpenApiJsonSerializer.SystemTextJson);
            Assert.That(switched.SpecId, Is.EqualTo(original.SpecId));
            Assert.That(switched.RequiresPublication, Is.True);
            Assert.That(writer.Publish(switched), Is.True);
            Assert.That(
                File.ReadAllText(original.DefinitionPath),
                Does.Contain("OpenApiJsonSerializer.SystemTextJson"));

            OpenApiClientDefinitionPlan back = Prepare(
                OpenApiHttpTransport.HttpClient,
                OpenApiJsonSerializer.NewtonsoftJson);
            Assert.That(back.SpecId, Is.EqualTo(original.SpecId));
            Assert.That(writer.Publish(back), Is.True);
            Assert.That(File.ReadAllBytes(original.DefinitionPath), Is.EqualTo(originalBytes));
        }

        [Test]
        public void ADefinitionWrittenBeforeTheSelectionExistedIsAcceptedUnchanged()
        {
            const string SpecId = "0123456789abcdef0123456789abcdef";
            string identity = ComputeIdentity();
            string legacy =
                "// <auto-generated by UnityOpenApiCodeGen.SourceGenerator>\n" +
                "// Client identity SHA-256: " + identity + "\n" +
                "// Spec ID: " + SpecId + "\n" +
                "// Changes to this file will be replaced by the next Generate operation.\n" +
                "#if OPENAPI_CODEGEN_SOURCE_GENERATOR\n" +
                "namespace " + Namespace + "\n" +
                "{\n" +
                "    [" + Prefix + "OpenApiClientDefinitionAttribute(\n" +
                "        \"" + SpecId + "\",\n" +
                "        \"PetStoreApi\",\n" +
                "        \"" + Namespace + "\",\n" +
                "        " + Prefix + "OpenApiDocumentFormat.Json)]\n" +
                "    public partial class PetStoreApi\n" +
                "    {\n" +
                "    }\n" +
                "}\n" +
                "#endif\n";
            // Earlier versions wrote the platform line ending.
            legacy = legacy.Replace("\n", Environment.NewLine);
            string path = Path.Combine(outputFolder, "PetStoreApi.OpenApiDefinition.cs");
            File.WriteAllText(path, legacy, new UTF8Encoding(false));

            OpenApiClientDefinitionPlan plan = Prepare(
                OpenApiHttpTransport.HttpClient,
                OpenApiJsonSerializer.NewtonsoftJson);

            Assert.That(plan.SpecId, Is.EqualTo(SpecId));
            Assert.That(plan.RequiresPublication, Is.False);
            Assert.That(writer.Publish(plan), Is.False);
            Assert.That(File.ReadAllText(path), Is.EqualTo(legacy));

            // The same file is also reusable when the user now picks another combination.
            OpenApiClientDefinitionPlan switched = Prepare(
                OpenApiHttpTransport.UnityWebRequest,
                OpenApiJsonSerializer.SystemTextJson);
            Assert.That(switched.SpecId, Is.EqualTo(SpecId));
            Assert.That(switched.RequiresPublication, Is.True);
        }

        [Test]
        public void ACarriageReturnDefinitionWithNamedArgumentsIsAccepted()
        {
            OpenApiClientDefinitionPlan plan = Prepare(
                OpenApiHttpTransport.UnityWebRequest,
                OpenApiJsonSerializer.SystemTextJson);
            Assert.That(writer.Publish(plan), Is.True);
            string path = plan.DefinitionPath;
            string crlf = Normalize(File.ReadAllText(path)).Replace("\n", "\r\n");
            File.WriteAllText(path, crlf, new UTF8Encoding(false));

            OpenApiClientDefinitionPlan again = Prepare(
                OpenApiHttpTransport.UnityWebRequest,
                OpenApiJsonSerializer.SystemTextJson);

            Assert.That(again.SpecId, Is.EqualTo(plan.SpecId));
        }

        [TestCase("        JsonSerializer = " + Prefix + "OpenApiJsonSerializer.SystemTextJson,\n" +
                  "        HttpTransport = " + Prefix + "OpenApiHttpTransport.UnityWebRequest)]\n", TestName = "WrongOrder")]
        [TestCase("        HttpTransport = " + Prefix + "OpenApiHttpTransport.Gopher)]\n", TestName = "UnknownName")]
        [TestCase("        HttpTransport = " + Prefix + "OpenApiHttpTransport.UnityWebRequest,\n" +
                  "        HttpTransport = " + Prefix + "OpenApiHttpTransport.UnityWebRequest)]\n", TestName = "Duplicate")]
        [TestCase("        Other = 1)]\n", TestName = "UnknownArgument")]
        [TestCase("        HttpTransport = " + Prefix + "OpenApiHttpTransport.HttpClient)]\n", TestName = "ExplicitDefault")]
        public void MalformedNamedArgumentsAreRejected(string namedArguments)
        {
            OpenApiClientDefinitionPlan plan = Prepare(
                OpenApiHttpTransport.UnityWebRequest,
                OpenApiJsonSerializer.SystemTextJson);
            Assert.That(writer.Publish(plan), Is.True);
            string source = Normalize(File.ReadAllText(plan.DefinitionPath));
            int start = source.IndexOf("        HttpTransport = ", StringComparison.Ordinal);
            int end = source.IndexOf("    public partial class", StringComparison.Ordinal);
            string tampered = source.Substring(0, start) + namedArguments + source.Substring(end);
            File.WriteAllText(plan.DefinitionPath, tampered, new UTF8Encoding(false));

            Assert.Throws<InvalidOperationException>(() => Prepare(
                OpenApiHttpTransport.UnityWebRequest,
                OpenApiJsonSerializer.SystemTextJson));
        }

        [Test]
        public void UndefinedSelectionValuesAreRejected()
        {
            Assert.Throws<ArgumentOutOfRangeException>(() => Prepare(
                (OpenApiHttpTransport)7,
                OpenApiJsonSerializer.NewtonsoftJson));
            Assert.Throws<ArgumentOutOfRangeException>(() => Prepare(
                OpenApiHttpTransport.HttpClient,
                (OpenApiJsonSerializer)7));
        }

        [Test]
        public void ChangingTheDocumentFormatKeepsTheSelection()
        {
            OpenApiClientDefinitionPlan plan = Prepare(
                OpenApiHttpTransport.UnityWebRequest,
                OpenApiJsonSerializer.SystemTextJson);

            OpenApiClientDefinitionPlan yaml = writer.WithDocumentFormat(plan, OpenApiDocumentFormat.Yaml);

            Assert.That(yaml.HttpTransport, Is.EqualTo(OpenApiHttpTransport.UnityWebRequest));
            Assert.That(yaml.JsonSerializer, Is.EqualTo(OpenApiJsonSerializer.SystemTextJson));
            string source = Encoding.UTF8.GetString(yaml.Content);
            Assert.That(source, Does.Contain("OpenApiDocumentFormat.Yaml,"));
            Assert.That(source, Does.Contain("OpenApiHttpTransport.UnityWebRequest"));
        }

        [Test]
        public void ResolveOutputTargetReportsTheAssemblyAndEngineReferenceSetting()
        {
            OutputTargetAssembly target = writer.ResolveOutputTarget(outputFolder);
